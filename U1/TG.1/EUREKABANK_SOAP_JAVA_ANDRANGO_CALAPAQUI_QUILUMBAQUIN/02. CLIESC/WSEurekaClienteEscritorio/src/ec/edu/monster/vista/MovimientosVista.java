    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        // DATO
        String cuenta = txtCuenta.getText();

        // PROCESO
        EurekaControlador control = new EurekaControlador();
        List<Movimiento> lista = control.traerMoviminetos(cuenta);

        // Crear un formato de fecha para mostrar solo año-mes-día
        SimpleDateFormat outputDateFormat = new SimpleDateFormat("yyyy-MM-dd");

        // Reporte
        DefaultTableModel tabla = (DefaultTableModel) reporte.getModel();
        tabla.setRowCount(0);  // Limpiar tabla antes de agregar datos

        for (Movimiento r : lista) {
            try {
                // Convertir XMLGregorianCalendar a Date
                XMLGregorianCalendar xmlFecha = r.getFecha();
                Date fechaDate = xmlFecha.toGregorianCalendar().getTime();

                // Formatear la fecha en el formato deseado
                String fechaFormateada = outputDateFormat.format(fechaDate);

                // Agregar la fila con la fecha formateada
                Object[] rowData = {
                    r.getCuenta(), 
                    r.getNromov(), 
                    fechaFormateada,  // Usamos la fecha formateada
                    r.getTipo(), 
                    r.getAccion(), 
                    r.getImporte()
                };
                tabla.addRow(rowData);
            } catch (Exception e) {
                System.out.println("Error al convertir la fecha: " + r.getFecha());
            }
        }
      
    }//GEN-LAST:event_btnBuscarActionPerformed

