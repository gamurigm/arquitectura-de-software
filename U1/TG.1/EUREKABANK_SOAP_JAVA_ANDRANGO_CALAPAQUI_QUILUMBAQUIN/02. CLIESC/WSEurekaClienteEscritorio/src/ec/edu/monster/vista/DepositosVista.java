    private void btnDepositoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositoActionPerformed
        //Datos
        String cuenta = txtCuenta.getText();
        double deposito = Double.parseDouble(txtDeposito.getText());
        
        //Proceso
        EurekaControlador control = new EurekaControlador();
        int estado = control.regDeposito(cuenta, deposito);
        
        String mensaje = "Deposito realizado satisfactoriamente!";
        if(estado ==-1){
            mensaje = "Error en el proceso, revise sus datos.";
        }
        JOptionPane.showMessageDialog(rootPane, mensaje);
    }//GEN-LAST:event_btnDepositoActionPerformed

